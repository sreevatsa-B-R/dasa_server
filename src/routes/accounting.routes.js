const express = require('express')
const router = express.Router()
const { protect } = require('../middleware/auth')
const { isAdmin, isAdminOrManager, isAdminOrAccountant } = require('../middleware/role')
const JournalEntry = require('../models/JournalEntry')
const { JOURNAL_TYPES } = require('../config/constants')
const { sendResponse, sendError } = require('../utils/response')

// Chart of accounts (static list for single shop — can be expanded)
const ACCOUNTS = [
  { code: 'CA001', name: 'Cash in Hand',     type: 'Asset' },
  { code: 'CA002', name: 'Bank Account',     type: 'Asset' },
  { code: 'CA003', name: 'Stock / Inventory',type: 'Asset' },
  { code: 'CA004', name: 'Accounts Receivable', type: 'Asset' },
  { code: 'LB001', name: 'Accounts Payable', type: 'Liability' },
  { code: 'LB002', name: 'GST Payable',      type: 'Liability' },
  { code: 'IN001', name: 'Sales Revenue',    type: 'Income' },
  { code: 'IN002', name: 'Old Gold Income',  type: 'Income' },
  { code: 'EX001', name: 'Purchase / Stock', type: 'Expense' },
  { code: 'EX002', name: 'Shop Expenses',    type: 'Expense' },
]

// Day-end records stored in memory (in production: persist to DB)
const dayEndRecords = []

// GET /api/v1/accounting/accounts
router.get('/accounts', protect, (req, res) => {
  sendResponse(res, 200, ACCOUNTS)
})

// POST /api/v1/accounting/journal  — manual entry
router.post('/journal', protect, isAdminOrAccountant, async (req, res, next) => {
  try {
    const entry = await JournalEntry.create({
      ...req.body,
      referenceType: 'Manual',
      isAutoGenerated: false,
      createdBy: req.user._id,
    })
    sendResponse(res, 201, entry, 'Journal entry created')
  } catch (err) { next(err) }
})

// GET /api/v1/accounting/journal
router.get('/journal', protect, isAdminOrAccountant, async (req, res, next) => {
  try {
    const { from, to, type, page = 1, limit = 30 } = req.query
    const filter = {}
    if (type) filter.type = type
    if (from || to) {
      filter.entryDate = {}
      if (from) filter.entryDate.$gte = new Date(from)
      if (to)   filter.entryDate.$lte = new Date(to)
    }
    const total = await JournalEntry.countDocuments(filter)
    const entries = await JournalEntry.find(filter)
      .populate('createdBy', 'name')
      .sort({ entryDate: -1 })
      .skip((page - 1) * limit)
      .limit(Number(limit))

    sendResponse(res, 200, { total, entries })
  } catch (err) { next(err) }
})

// POST /api/v1/accounting/day-end
router.post('/day-end', protect, isAdminOrAccountant, async (req, res, next) => {
  try {
    const { date, physicalCash, bankBalance, note } = req.body

    // Get total cash sales for the day from journal
    const startOfDay = new Date(date)
    const endOfDay = new Date(date)
    endOfDay.setHours(23, 59, 59, 999)

    const salesEntries = await JournalEntry.find({
      type: JOURNAL_TYPES.SALE,
      entryDate: { $gte: startOfDay, $lte: endOfDay },
    })
    const expectedCash = salesEntries.reduce((sum, e) => sum + e.amount, 0)
    const difference = physicalCash - expectedCash

    const record = { date, expectedCash, physicalCash, bankBalance, difference, note, closedBy: req.user.name }
    dayEndRecords.push(record)

    sendResponse(res, 200, record, difference === 0 ? 'Day closed — cash matches' : `Day closed — discrepancy: ₹${difference}`)
  } catch (err) { next(err) }
})

// GET /api/v1/accounting/day-end/:date
router.get('/day-end/:date', protect, isAdminOrAccountant, (req, res) => {
  const record = dayEndRecords.find(r => r.date === req.params.date)
  if (!record) return sendError(res, 404, 'No day-end record for this date')
  sendResponse(res, 200, record)
})

// GET /api/v1/accounting/cashbook
router.get('/cashbook', protect, isAdminOrAccountant, async (req, res, next) => {
  try {
    const { from, to } = req.query
    const filter = { type: { $in: [JOURNAL_TYPES.SALE, JOURNAL_TYPES.PAYMENT, JOURNAL_TYPES.RECEIPT] } }
    if (from || to) {
      filter.entryDate = {}
      if (from) filter.entryDate.$gte = new Date(from)
      if (to)   filter.entryDate.$lte = new Date(to)
    }
    const entries = await JournalEntry.find(filter).sort({ entryDate: 1 })
    sendResponse(res, 200, entries)
  } catch (err) { next(err) }
})

// GET /api/v1/accounting/gst-summary?from=&to=
router.get('/gst-summary', protect, isAdminOrAccountant, async (req, res, next) => {
  try {
    const { from, to } = req.query
    const SalesInvoice = require('../models/SalesInvoice')
    const PurchaseOrder = require('../models/PurchaseOrder')

    const dateFilter = {}
    if (from) dateFilter.$gte = new Date(from)
    if (to)   dateFilter.$lte = new Date(to)

    const salesFilter = Object.keys(dateFilter).length ? { invoiceDate: dateFilter, isReturn: false } : { isReturn: false }
    const purchaseFilter = Object.keys(dateFilter).length ? { createdAt: dateFilter, orderType: 'supplier' } : { orderType: 'supplier' }

    const salesAgg = await SalesInvoice.aggregate([
      { $match: salesFilter },
      { $group: { _id: null, totalGstCollected: { $sum: '$gstAmount' }, totalSales: { $sum: '$totalAmount' } } }
    ])

    const purchaseAgg = await PurchaseOrder.aggregate([
      { $match: { ...purchaseFilter, gstAmount: { $gt: 0 } } },
      { $group: { _id: null, totalGstPaid: { $sum: '$gstAmount' }, totalPurchases: { $sum: '$totalInvoiceAmt' } } }
    ])

    const gstCollected = salesAgg[0]?.totalGstCollected || 0
    const gstPaid      = purchaseAgg[0]?.totalGstPaid || 0
    const netGstPayable = parseFloat((gstCollected - gstPaid).toFixed(2))

    sendResponse(res, 200, {
      period: { from, to },
      totalSales:     salesAgg[0]?.totalSales || 0,
      gstCollected,
      totalPurchases: purchaseAgg[0]?.totalPurchases || 0,
      gstPaid,
      netGstPayable,
    })
  } catch (err) { next(err) }
})

module.exports = router
