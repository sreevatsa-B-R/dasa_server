const mongoose = require('mongoose')
const { JOURNAL_TYPES } = require('../config/constants')

const journalEntrySchema = new mongoose.Schema({
  entryDate: {
    type: Date,
    default: Date.now,
    required: true,
  },
  type: {
    type: String,
    enum: Object.values(JOURNAL_TYPES),
    required: true,
  },
  debitAccount:  { type: String, required: true },
  creditAccount: { type: String, required: true },
  amount:        { type: Number, required: true },
  narration:     { type: String, trim: true },
  // Reference to source document
  referenceType: {
    type: String,
    enum: ['SalesInvoice', 'PurchaseOrder', 'CustomerOrder', 'Manual'],
  },
  referenceId:   { type: mongoose.Schema.Types.ObjectId },
  isAutoGenerated: { type: Boolean, default: false },
  createdBy:     { type: mongoose.Schema.Types.ObjectId, ref: 'User' },
}, { timestamps: true })

module.exports = mongoose.model('JournalEntry', journalEntrySchema)
